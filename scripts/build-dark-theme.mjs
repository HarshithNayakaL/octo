// Generates src/dark.css from the light stylesheets: every colour declaration is
// mapped to a dark-theme equivalent and scoped under :root[data-theme="dark"].
// Run with `npm run theme:dark` after changing colours in the light theme.
import { readFileSync, writeFileSync } from "node:fs";
import postcss from "postcss";

const sources = [
  "src/styles.css",
  "src/control-refinements.css",
  "src/octo.css",
  "src/showcase.css",
];
const colorPattern = /#[0-9a-fA-F]{3,8}\b|rgba?\([^)]*\)|\b(white|black)\b/g;

function parse(token) {
  if (token === "white") return [255, 255, 255, 1];
  if (token === "black") return [0, 0, 0, 1];
  if (token.startsWith("#")) {
    let hex = token.slice(1);
    if (hex.length === 3 || hex.length === 4)
      hex = [...hex].map((c) => c + c).join("");
    const n = (i) => parseInt(hex.slice(i, i + 2), 16);
    return [n(0), n(2), n(4), hex.length === 8 ? n(6) / 255 : 1];
  }
  const parts = token.match(/[\d.]+/g).map(Number);
  return [parts[0], parts[1], parts[2], parts[3] ?? 1];
}
const toHsl = ([r, g, b]) => {
  r /= 255;
  g /= 255;
  b /= 255;
  const max = Math.max(r, g, b);
  const min = Math.min(r, g, b);
  const l = (max + min) / 2;
  if (max === min) return [0, 0, l];
  const d = max - min;
  const s = l > 0.5 ? d / (2 - max - min) : d / (max + min);
  const h =
    max === r
      ? (g - b) / d + (g < b ? 6 : 0)
      : max === g
        ? (b - r) / d + 2
        : (r - g) / d + 4;
  return [h * 60, s, l];
};
const fromHsl = (h, s, l) => {
  const k = (n) => (n + h / 30) % 12;
  const a = s * Math.min(l, 1 - l);
  const f = (n) =>
    l - a * Math.max(-1, Math.min(k(n) - 3, Math.min(9 - k(n), 1)));
  return [f(0), f(8), f(4)].map((v) => Math.round(v * 255));
};
const format = ([r, g, b], a) =>
  a >= 1
    ? "#" + [r, g, b].map((v) => v.toString(16).padStart(2, "0")).join("")
    : `rgba(${r}, ${g}, ${b}, ${Number(a.toFixed(3))})`;
const clamp = (v, lo, hi) => Math.min(hi, Math.max(lo, v));

/**
 * role: "fg" for text/icons, "bg" for surfaces, "line" for borders, "shadow".
 * The dark theme is AMOLED: the page is true black, surfaces sit a hair above it,
 * and greys are neutral so the blue accent is the only colour that glows.
 */
const GREY = [230, 0.06];
function mapColor(token, role) {
  const [r, g, b, a] = parse(token);
  const [h, s, l] = toHsl([r, g, b]);
  const neutral = s < 0.22 || (l > 0.93 && s < 0.6);
  if (role === "shadow") return format([0, 0, 0], clamp(a * 2.4, 0.3, 0.7));
  if (role === "fg") {
    if (neutral)
      return format(fromHsl(...GREY, clamp(1.02 - l * 0.92, 0.5, 0.95)), a);
    // Accent text: keep the hue, lift it so it reads on black.
    return format(
      fromHsl(h, Math.min(s, 0.85), clamp(Math.max(l, 0.7), 0.66, 0.84)),
      a,
    );
  }
  if (role === "line") {
    if (neutral)
      return format(
        fromHsl(...GREY, clamp(0.12 + (0.95 - l) * 0.5, 0.11, 0.2)),
        a,
      );
    if (l > 0.6)
      return format(
        fromHsl(h, Math.min(s, 0.5), clamp(0.16 + (1 - l) * 0.4, 0.15, 0.3)),
        a,
      );
    return format(fromHsl(h, s, clamp(l + 0.1, 0.28, 0.55)), a);
  }
  // Backgrounds
  if (neutral) {
    // White cards become near-black panels; light greys become slightly raised ones.
    if (l > 0.5)
      return format(
        fromHsl(...GREY, clamp(0.035 + (1 - l) * 1.3, 0.035, 0.14)),
        a,
      );
    return format(fromHsl(...GREY, clamp(0.92 - l * 0.4, 0.75, 0.94)), a);
  }
  // Light tints become deep tints; saturated fills (primary buttons) keep their colour.
  if (l > 0.82)
    return format(
      fromHsl(h, Math.min(s, 0.55), clamp(0.06 + (1 - l) * 0.35, 0.06, 0.13)),
      a,
    );
  if (l < 0.45) return format(fromHsl(h, s, clamp(l + 0.08, 0.32, 0.5)), a);
  return format(fromHsl(h, s * 0.8, clamp(l * 0.6, 0.2, 0.45)), a);
}
const roleFor = (prop) =>
  /shadow/.test(prop)
    ? "shadow"
    : /^(color|fill|stroke|caret-color|accent-color|outline-color|text-decoration-color)$/.test(
          prop,
        ) ||
        (prop.startsWith("--") && /(ink|muted|accent|blue)$/.test(prop))
      ? "fg"
      : /border|outline/.test(prop) ||
          prop === "--line" ||
          prop === "--blue-line"
        ? "line"
        : "bg";

const out = postcss.root();
out.append(
  postcss.comment({
    text: " Generated by scripts/build-dark-theme.mjs. Do not edit by hand. ",
  }),
);
for (const file of sources) {
  const root = postcss.parse(readFileSync(file, "utf8"), { from: file });
  root.walkRules((rule) => {
    if (rule.parent?.type === "atrule" && /keyframes/.test(rule.parent.name))
      return;
    const decls = [];
    rule.walkDecls((decl) => {
      if (!colorPattern.test(decl.value)) return;
      colorPattern.lastIndex = 0;
      // Brand variables that the dark theme sets explicitly below.
      if (["--blue", "--accent"].includes(decl.prop)) return;
      const role = roleFor(decl.prop);
      decls.push(
        postcss.decl({
          prop: decl.prop,
          value: decl.value.replace(colorPattern, (t) => mapColor(t, role)),
          important: decl.important,
        }),
      );
    });
    if (!decls.length) return;
    const scoped = rule.clone({ nodes: [] });
    scoped.selectors = rule.selectors.map((sel) =>
      sel.startsWith(":root")
        ? sel.replace(":root", ':root[data-theme="dark"]')
        : `:root[data-theme="dark"] ${sel}`,
    );
    decls.forEach((d) => scoped.append(d));
    let target = out;
    // Keep media queries around rules that were inside them.
    const media = [];
    for (let p = rule.parent; p && p.type === "atrule"; p = p.parent)
      media.unshift(p);
    for (const m of media) {
      const wrapper = postcss.atRule({ name: m.name, params: m.params });
      target.append(wrapper);
      target = wrapper;
    }
    target.append(scoped);
  });
}
out.append(
  postcss.parse(`
:root[data-theme="dark"] {
  color-scheme: dark;
  --ink: #f4f5f8;
  --blue: #8ea6ff;
  --accent: #8ea6ff;
  --blue-soft: #0b1129;
  --blue-line: #1d2850;
  background: #000;
}
:root[data-theme="dark"] body,
:root[data-theme="dark"] #root {
  background: #000;
}
/* Primary actions keep the brand blue as a fill with white text. */
:root[data-theme="dark"] .primary,
:root[data-theme="dark"] .option-chip.on,
:root[data-theme="dark"] .area-chip.on .area-check,
:root[data-theme="dark"] .slide-confirm-knob {
  background: #3152f0 !important;
  border-color: #3152f0 !important;
  color: #fff !important;
}
:root[data-theme="dark"] .voice-fab,
:root[data-theme="dark"] .voice-mic {
  background: linear-gradient(135deg, #4a6bff, #3152f0) !important;
  color: #fff !important;
}
:root[data-theme="dark"] .voice-mic.recording {
  background: #c43a2f !important;
}
:root[data-theme="dark"] .voice-orb span {
  background: rgba(255, 255, 255, 0.85);
}
/* The showcase surfaces (hero, bento, trust strip) are styled by hand in src/amoled.css. */
:root[data-theme="dark"] .primary.danger {
  background: #c43a2f !important;
  border-color: #c43a2f !important;
}
:root[data-theme="dark"] .markdown a,
:root[data-theme="dark"] a {
  color: #8fa8ff;
}
:root[data-theme="dark"] canvas.mascot {
  filter: brightness(1.04);
}
`),
);
writeFileSync("src/dark.css", out.toString() + "\n");
console.log(`src/dark.css written from ${sources.length} stylesheets`);
